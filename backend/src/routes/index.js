import {Router} from 'express';
import {login} from '../controllers/authController.js';
import {dashboard} from '../controllers/dashboardController.js';
import {dropdowns,employees} from '../controllers/configController.js';
import * as a from '../controllers/assetController.js';
import * as t from '../controllers/ticketController.js';
import {auth,adminOnly} from '../middleware/auth.js';
const r=Router();
r.post('/auth/login',login);
r.get('/dashboard',auth,dashboard);
r.get('/config/dropdowns',auth,dropdowns);
r.get('/employees',auth,employees);
r.get('/assets',auth,a.listAssets);
r.get('/assets/:id',auth,a.getAsset);
r.post('/assets',auth,a.addAsset);
r.post('/assets/:id/transfer',auth,a.transferAsset);
r.post('/assets/:id/confirm-receipt',auth,a.confirmReceipt);
r.post('/assets/:id/remove',auth,a.removeAsset);
r.post('/assets/:id/custodian',auth,a.assignCustodian);
r.get('/approvals',auth,adminOnly,a.approvals);
r.post('/approvals/:id/approve',auth,adminOnly,a.approve);
r.post('/approvals/:id/reject',auth,adminOnly,a.reject);
r.get('/tickets',auth,t.tickets);
r.patch('/tickets/:id',auth,adminOnly,t.updateTicket);
export default r;
